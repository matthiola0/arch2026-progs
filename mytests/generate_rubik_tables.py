#!/usr/bin/env python3
"""Generate partial IDA* pattern databases; no complete solution table is shipped."""

import argparse
import itertools
import json
from collections import deque
from pathlib import Path

SOURCE = ((1, 4, 2, 0, 3, 5, 6), (0, 1, 2, 4, 5, 6, 3),
          (0, 2, 5, 3, 1, 4, 6))
TWIST = ((1, 2, 0, 2, 1, 0, 0), (0, 0, 0, 1, 2, 1, 2), (0,) * 7)


def distances(moves, root, width=1, other=None):
    count = len(moves[0])
    result = bytearray([255]) * (count if other is None else count * width)
    result[root] = 0
    queue = deque([root])
    while queue:
        here = queue.popleft()
        o, s = divmod(here, width)
        for face in range(3):
            no, ns = o, s
            for _ in range(3):
                no = moves[face][no]
                if other is not None:
                    ns = other[face][ns]
                there = no * width + ns
                if result[there] == 255:
                    result[there] = result[here] + 1
                    queue.append(there)
    assert 255 not in result
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--mode", choices=("basic", "pattern"), default="pattern")
    parser.add_argument("--subset", default="235")
    parser.add_argument("--out", type=Path, default=Path("src/rubik"))
    args = parser.parse_args()
    subset = tuple(int(x) - 1 for x in args.subset)
    assert len(subset) == 3 and len(set(subset)) == 3 and all(0 <= x < 7 for x in subset)

    permutations = list(itertools.permutations(range(7)))
    p_index = {p: i for i, p in enumerate(permutations)}
    orientations = [o + ((-sum(o)) % 3,) for o in itertools.product(range(3), repeat=6)]
    o_index = {o: i for i, o in enumerate(orientations)}
    pm = [[p_index[tuple(p[k] for k in source)] for p in permutations] for source in SOURCE]
    om = [[o_index[tuple((o[k] + t) % 3 for k, t in zip(source, twist))]
           for o in orientations] for source, twist in zip(SOURCE, TWIST)]
    pd = distances(pm, 0)
    arrays = [("rb_perm", "uint16_t", [v for row in pm for v in row], (3, 5040)),
              ("rb_orient", "uint16_t", [v for row in om for v in row], (3, 729)),
              ("rb_pdist", "uint8_t", pd, (5040,))]
    metadata = {"mode": args.mode, "permutation_maximum": max(pd)}
    if args.mode == "basic":
        od = distances(om, 0)
        arrays.append(("rb_odist", "uint8_t", od, (729,)))
        metadata["orientation_maximum"] = max(od)
    else:
        positions = list(itertools.permutations(range(7), 3))
        s_index = {s: i for i, s in enumerate(positions)}
        destinations = [tuple(source.index(i) for i in range(7)) for source in SOURCE]
        sm = [[s_index[tuple(destination[k] for k in s)] for s in positions]
              for destination in destinations]
        pdb = distances(om, s_index[subset], 210, sm)
        assert max(pdb) < 16
        packed = [pdb[i] | (pdb[i + 1] << 4) for i in range(0, len(pdb), 2)]
        assert all(((packed[i >> 1] >> ((i & 1) << 2)) & 15) == value
                   for i, value in enumerate(pdb))
        ps = [s_index[tuple(p.index(k) for k in subset)] for p in permutations]
        arrays.extend((("rb_subset", "uint8_t", ps, (5040,)),
                       ("rb_ooffset", "uint32_t", [i * 105 for i in range(729)], (729,)),
                       ("rb_pdb", "uint8_t", packed, (len(packed),))))
        metadata.update(subset=args.subset, pattern_states=len(pdb),
                        pattern_maximum=max(pdb), pattern_packed_bytes=len(packed))

    args.out.mkdir(parents=True, exist_ok=True)
    strong = int(args.mode == "pattern")
    c = ["/* Generated by mytests/generate_rubik_tables.py. Do not edit. */",
         "#pragma once", "#include <stdint.h>", f"#define RB_STRONG {strong}", ""]
    asm = ["# Generated by mytests/generate_rubik_tables.py. Do not edit.",
           f".equ RB_STRONG, {strong}", ".section .rodata"]
    total = 0
    for name, ctype, values, shape in arrays:
        size = {"uint8_t": 1, "uint16_t": 2, "uint32_t": 4}[ctype]
        total = (total + size - 1) // size * size + len(values) * size
        dims = "".join(f"[{d}]" for d in shape)
        c.append(f"static const {ctype} {name}{dims} = {{")
        rows = [values] if len(shape) == 1 else [values[i:i + shape[1]]
                                                for i in range(0, len(values), shape[1])]
        for row in rows:
            if len(shape) > 1:
                c.append("    {")
            c.extend("        " + ", ".join(map(str, row[i:i + 16])) + ","
                     for i in range(0, len(row), 16))
            if len(shape) > 1:
                c.append("    },")
        c.append("};\n")
        asm.extend((f".balign {size}", name + ":"))
        directive = {1: ".byte", 2: ".half", 4: ".word"}[size]
        asm.extend("    " + directive + " " + ", ".join(map(str, values[i:i + 16]))
                   for i in range(0, len(values), 16))
    (args.out / "rubik_tables.h").write_text("\n".join(c), encoding="utf-8")
    (args.out / "rubik_tables.inc").write_text("\n".join(asm) + "\n", encoding="utf-8")
    # The fixed Makefile does not track GNU assembler .include dependencies.
    assembly = args.out / "rubik.S"
    if assembly.is_file():
        assembly.touch()
    metadata["table_bytes_including_alignment"] = total
    print(json.dumps(metadata, indent=2))


if __name__ == "__main__":
    main()
